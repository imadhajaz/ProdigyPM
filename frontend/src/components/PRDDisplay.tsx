"use client";

import React from "react";
import { motion } from "framer-motion";

interface PRDData {
  feature?: string;
  prd?: string;
  status?: string;
  [key: string]: any;
}

interface PRDDisplayProps {
  prdData: PRDData;
}

export default function PRDDisplay({ prdData }: PRDDisplayProps) {
  const prdText = prdData.prd || "";

  // Parse PRD text into sections
  const parsePRD = (text: string) => {
    const sections: { [key: string]: string } = {};
    const lines = text.split("\n");

    let currentSection = "overview";
    let currentContent: string[] = [];

    for (const line of lines) {
      const trimmedLine = line.trim();

      // Detect section headers
      if (trimmedLine.match(/^#+\s*(Overview|Goals|Requirements|User Stories|Acceptance Criteria|Overview:)/i)) {
        if (currentContent.length > 0) {
          sections[currentSection] = currentContent.join("\n").trim();
        }
        currentSection = "overview";
        currentContent = [];
      } else if (trimmedLine.match(/^#+\s*(Goals|Goals:)/i)) {
        if (currentContent.length > 0) {
          sections[currentSection] = currentContent.join("\n").trim();
        }
        currentSection = "goals";
        currentContent = [];
      } else if (trimmedLine.match(/^#+\s*(Requirements|Requirements:)/i)) {
        if (currentContent.length > 0) {
          sections[currentSection] = currentContent.join("\n").trim();
        }
        currentSection = "requirements";
        currentContent = [];
      } else if (trimmedLine.match(/^#+\s*(User Stories|User Stories:)/i)) {
        if (currentContent.length > 0) {
          sections[currentSection] = currentContent.join("\n").trim();
        }
        currentSection = "userStories";
        currentContent = [];
      } else if (trimmedLine.match(/^#+\s*(Acceptance Criteria|Acceptance Criteria:)/i)) {
        if (currentContent.length > 0) {
          sections[currentSection] = currentContent.join("\n").trim();
        }
        currentSection = "acceptanceCriteria";
        currentContent = [];
      } else if (trimmedLine.length > 0) {
        currentContent.push(line);
      }
    }

    if (currentContent.length > 0) {
      sections[currentSection] = currentContent.join("\n").trim();
    }

    return sections;
  };

  const formatContent = (content: string) => {
    const lines = content.split("\n");
    const formatted: JSX.Element[] = [];

    lines.forEach((line, index) => {
      const trimmed = line.trim();

      if (trimmed.startsWith("- ") || trimmed.startsWith("* ")) {
        formatted.push(
          <li key={index} className="ml-4 mb-2 text-slate-300 flex items-start gap-2">
            <span className="text-cyan-500 mt-1.5 w-1.5 h-1.5 rounded-full flex-shrink-0 bg-cyan-500" />
            <span>{trimmed.substring(2)}</span>
          </li>
        );
      } else if (trimmed.match(/^\d+\.\s/)) {
        formatted.push(
          <li key={index} className="ml-4 mb-2 text-slate-300 list-decimal marker:text-cyan-500 pl-1">
            {trimmed.replace(/^\d+\.\s/, "")}
          </li>
        );
      } else if (trimmed.length > 0) {
        formatted.push(
          <p key={index} className="mb-3 text-slate-300 leading-relaxed">
            {trimmed}
          </p>
        );
      }
    });

    return formatted;
  };

  const sections = parsePRD(prdText);

  // Fallback for raw text
  if (Object.keys(sections).length === 0) {
    return (
      <div className="glass rounded-xl p-8 border border-white/10">
        <h2 className="text-2xl font-bold text-white mb-4">Product Requirements Document</h2>
        <div className="prose prose-invert max-w-none">
          <pre className="whitespace-pre-wrap text-sm text-slate-300 font-mono bg-black/30 p-4 rounded-lg">
            {prdText}
          </pre>
        </div>
      </div>
    );
  }

  return (
    <motion.div
      initial={{ opacity: 0 }}
      animate={{ opacity: 1 }}
      className="glass rounded-2xl border border-white/10 p-8 max-w-5xl mx-auto shadow-2xl relative overflow-hidden"
    >
      <div className="absolute top-0 right-0 w-64 h-64 bg-cyan-500/10 blur-[100px] rounded-full pointer-events-none" />

      {/* Header */}
      <div className="border-b border-white/10 pb-6 mb-8 flex justify-between items-start relative z-10">
        <div>
          <h1 className="text-4xl font-bold bg-gradient-to-r from-white to-slate-400 bg-clip-text text-transparent mb-2">
            {prdData.feature || "Product Requirements Document"}
          </h1>
          <p className="text-slate-400 text-sm">Generated by ProdigyPM AI Consultant</p>
        </div>
        {prdData.status && (
          <span className="px-4 py-1.5 bg-green-500/20 text-green-300 rounded-full text-sm font-medium border border-green-500/30 shadow-lg shadow-green-500/10">
            {prdData.status}
          </span>
        )}
      </div>

      <div className="grid grid-cols-1 gap-8 relative z-10">
        {/* Overview & Goals Row */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-8">
          {sections.overview && (
            <section className="bg-white/5 rounded-xl p-6 border border-white/5 hover:border-blue-500/30 transition-colors">
              <h2 className="text-xl font-bold text-blue-400 mb-4 flex items-center gap-2">
                <span className="w-8 h-8 rounded-lg bg-blue-500/20 flex items-center justify-center text-blue-300 text-sm">📋</span>
                Overview
              </h2>
              <div className="text-slate-300 space-y-2">
                {formatContent(sections.overview)}
              </div>
            </section>
          )}

          {sections.goals && (
            <section className="bg-white/5 rounded-xl p-6 border border-white/5 hover:border-green-500/30 transition-colors">
              <h2 className="text-xl font-bold text-green-400 mb-4 flex items-center gap-2">
                <span className="w-8 h-8 rounded-lg bg-green-500/20 flex items-center justify-center text-green-300 text-sm">🎯</span>
                Goals
              </h2>
              <ul className="list-none space-y-2">
                {formatContent(sections.goals)}
              </ul>
            </section>
          )}
        </div>

        {/* Requirements Section */}
        {sections.requirements && (
          <section className="bg-white/5 rounded-xl p-6 border border-white/5 hover:border-purple-500/30 transition-colors">
            <h2 className="text-xl font-bold text-purple-400 mb-4 flex items-center gap-2">
              <span className="w-8 h-8 rounded-lg bg-purple-500/20 flex items-center justify-center text-purple-300 text-sm">📝</span>
              Functional Requirements
            </h2>
            <div className="space-y-2">
              {formatContent(sections.requirements)}
            </div>
          </section>
        )}

        {/* User Stories */}
        {sections.userStories && (
          <section className="bg-white/5 rounded-xl p-6 border border-white/5 hover:border-pink-500/30 transition-colors">
            <h2 className="text-xl font-bold text-pink-400 mb-4 flex items-center gap-2">
              <span className="w-8 h-8 rounded-lg bg-pink-500/20 flex items-center justify-center text-pink-300 text-sm">👤</span>
              User Stories
            </h2>
            <div className="space-y-4">
              {formatContent(sections.userStories)}
            </div>
          </section>
        )}

        {/* Acceptance Criteria */}
        {sections.acceptanceCriteria && (
          <section className="bg-white/5 rounded-xl p-6 border border-white/5 hover:border-yellow-500/30 transition-colors">
            <h2 className="text-xl font-bold text-yellow-400 mb-4 flex items-center gap-2">
              <span className="w-8 h-8 rounded-lg bg-yellow-500/20 flex items-center justify-center text-yellow-300 text-sm">✅</span>
              Acceptance Criteria
            </h2>
            <div className="space-y-2 bg-yellow-500/5 p-4 rounded-lg border border-yellow-500/10">
              {formatContent(sections.acceptanceCriteria)}
            </div>
          </section>
        )}
      </div>

      <div className="mt-12 pt-6 border-t border-white/10 text-center">
        <p className="text-slate-500 text-sm flex items-center justify-center gap-2">
          <span className="w-2 h-2 rounded-full bg-green-500 animate-pulse"></span>
          AI-Generated Content • Reviewed by ProdigyPM
        </p>
      </div>
    </motion.div>
  );
}
