"""
Jira Sync Service - Convert subprojects to Jira tickets
"""
import logging
from typing import List, Dict

logger = logging.getLogger(__name__)


def subproject_to_jira_issue(subproject: Dict, project_key: str = "PROD") -> Dict:
    """
    Convert a subproject to a Jira issue format.
    
    Args:
        subproject: Subproject dictionary with keys: title, description, department, etc.
        project_key: Jira project key
        
    Returns:
        Dictionary formatted for Jira issue creation
    """
    # Map effort estimate to priority
    effort_to_priority = {
        "Small": "Low",
        "Medium": "Medium",
        "Large": "High",
        "X-Large": "High"
    }
    
    # Build description from subproject details
    description_parts = [subproject.get("description", "")]
    
    # Add acceptance criteria
    if subproject.get("acceptance_criteria"):
        description_parts.append("\n\n**Acceptance Criteria:**")
        for criterion in subproject["acceptance_criteria"]:
            description_parts.append(f"- {criterion}")
    
    # Add dependencies
    if subproject.get("dependencies"):
        description_parts.append("\n\n**Dependencies:**")
        for dep in subproject["dependencies"]:
            description_parts.append(f"- {dep}")
    
    # Add metadata
    description_parts.append(f"\n\n---\n*Generated by ProdigyPM*")
    description_parts.append(f"*Department: {subproject.get('department', 'Unknown')}*")
    description_parts.append(f"*Effort Estimate: {subproject.get('effort_estimate', 'Unknown')} ({subproject.get('effort_days', 0)} days)*")
    
    # Format title with department prefix
    department = subproject.get("department", "General")
    title = subproject.get("title", "Untitled Subproject")
    summary = f"[{department}] {title}"
    
    return {
        "summary": summary,
        "description": "\n".join(description_parts),
        "type": "Task",  # Can be customized: Task, Story, Bug, etc.
        "priority": effort_to_priority.get(subproject.get("effort_estimate", "Medium"), "Medium"),
        "labels": [
            subproject.get("department", "General"),
            f"effort-{subproject.get('effort_estimate', 'Medium').lower()}",
            "prodigypm-generated"
        ],
        "subproject_id": subproject.get("subproject_id"),  # Keep reference
        "original_priority": subproject.get("priority", "Medium")
    }


def subprojects_to_jira_issues(subprojects: List[Dict], project_key: str = "PROD") -> List[Dict]:
    """
    Convert multiple subprojects to Jira issue format.
    
    Args:
        subprojects: List of subproject dictionaries
        project_key: Jira project key
        
    Returns:
        List of Jira issue dictionaries ready for creation
    """
    jira_issues = []
    for subproject in subprojects:
        try:
            jira_issue = subproject_to_jira_issue(subproject, project_key)
            jira_issues.append(jira_issue)
        except Exception as e:
            logger.error(f"Failed to convert subproject {subproject.get('subproject_id')} to Jira issue: {e}")
    
    logger.info(f"Converted {len(jira_issues)}/{len(subprojects)} subprojects to Jira issues")
    return jira_issues

